/**
 * 실제로 쓰는 공휴일 = 내장 목록 + 사용자가 추가한 날 − 사용자가 뺀 날 (규칙 15)
 */
export function effectiveHolidays(
  added: readonly DateString[] = [],
  removed: readonly DateString[] = [],
): Set<DateString> {
  const set = new Set<DateString>(Object.keys(BUILT_IN_HOLIDAYS));
  for (const d of added) set.add(d);
  for (const d of removed) set.delete(d);
  return set;
}

/** 공휴일 이름 (내장 목록에 없거나 사용자가 추가한 날이면 "공휴일") */
export function holidayName(date: DateString, holidays: ReadonlySet<DateString>): string | null {
  if (!holidays.has(date)) return null;
  return BUILT_IN_HOLIDAYS[date] ?? "공휴일";
}
